// Compact the already-grouped system variable facts without re-capturing them.
const CODES = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ!@$%^&*+=?|:;<>~()[]{}#-'

export function renderSystemVariables(groups, version) {
  const ordered = [...groups.keys()].sort().sort((a, b) => a[2].localeCompare(b[2])).map((header) => {
    const [flags, prefix] = header.split('\t')
    const records = groups.get(header)
    return { flags, prefix: prefix.slice(0, -1), rows: [...records.keys()].sort().map((fields) => [records.get(fields), fields]) }
  })

  const counts = new Map()
  for (const { prefix, rows } of ordered) {
    for (const name of [prefix, ...rows.flatMap(([names]) => names)]) {
      for (const word of name.split('_')) if (word.length > 1) counts.set(word, (counts.get(word) ?? 0) + 1)
    }
  }
  const words = [...counts].sort(([a, ac], [b, bc]) => bc * (b.length - 1) - ac * (a.length - 1))
    .slice(0, CODES.length).map(([word]) => word)
  const codes = new Map(words.map((word, i) => [word, CODES[i]]))
  const pack = (name) => {
    if (!/^[a-z0-9]+(?:_[a-z0-9]+)*$/.test(name)) return name === '' ? '' : '\\' + name
    let result = ''
    let previousRaw = false
    for (const word of name.split('_')) {
      const token = codes.get(word)
      const raw = token === undefined
      if (previousRaw && raw) result += '_'
      result += token ?? word
      previousRaw = raw
    }
    return result
  }

  const groupsText = ordered.map(({ flags, prefix, rows }) =>
    [flags + '\t' + pack(prefix), ...rows.map(([names, fields]) => names.map(pack).join(' ') + '\t' + fields)].join('\n'))
  // Keep the original separators if either printable one occurs in the facts.
  const printable = groupsText.every((group) => !group.includes("'") && !group.includes('`'))
  const rowSeparator = printable ? "'" : '\n'
  const fieldSeparator = printable ? '`' : '\t'
  const body = groupsText.map((group, i) => {
    const packed = group.replaceAll('\n', rowSeparator).replaceAll('\t', fieldSeparator)
    return '  ' + JSON.stringify(packed + (i + 1 < groupsText.length ? rowSeparator.repeat(2) : ''))
  }).join(' +\n')
  return `// Generated by tools/capture-variables.mjs from MySQL ${version}. Do not edit.
//
// Two row separators start a group. The field separator divides each row.
// Each group begins with flags (scope G global, S
// session, B both; r read-only, g settable only by SET GLOBAL, or w
// settable; type b boolean, i integer, d double, s string; n when its
// default is NULL, z when a session's DEFAULT is 0) and a shared name
// prefix, possibly empty. Each following line gives the space-separated
// name suffixes sharing a SHOW VARIABLES default (0 or 1 for booleans,
// NUL for a machine value) and the same numeric bounds.
//
// Name tokens substitute repeated underscore-delimited words. An underscore
// separates adjacent raw words. An initial backslash carries an unencoded name.
// Nonnegative integers use hexadecimal when shorter. The values are facts
// asked of the server (ground rule 7).
export const VARIABLE_NAME_CODES = ${JSON.stringify(CODES)}
export const VARIABLE_NAME_WORDS = ${JSON.stringify(words.join(' '))}
export const VARIABLE_ROW_SEPARATOR = ${JSON.stringify(rowSeparator)}
export const VARIABLE_FIELD_SEPARATOR = ${JSON.stringify(fieldSeparator)}
export const SYSTEM_VARIABLES =
${body}
`
}
