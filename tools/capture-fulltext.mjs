#!/usr/bin/env node
// M5.26 — InnoDB's full-text parameters, from a real MySQL, into `@myjs/core`.
//
// A FULLTEXT index leaves out words shorter than `innodb_ft_min_token_size`,
// longer than `innodb_ft_max_token_size`, and those on InnoDB's default
// stopword list. Which words those are is runtime data the server publishes
// (`INFORMATION_SCHEMA.INNODB_FT_DEFAULT_STOPWORD` and two variables), so,
// as D-39 does for keywords, this asks the server instead of reading MySQL's
// source. What is committed is the words and two numbers, never source text,
// so ground rule 7 holds.
//
// Usage:
//   node tools/capture-fulltext.mjs --host 127.0.0.1 --port 3306 --user root --password root
import { writeFileSync } from 'node:fs'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

const run = promisify(execFile)

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`)
  return i === -1 ? fallback : process.argv[i + 1]
}

const HOST = arg('host', '127.0.0.1')
const PORT = arg('port', '3306')
const USER = arg('user', 'root')
const PASSWORD = arg('password', 'root')
const OUT = arg('out', new URL('../packages/core/src/sql/fulltext-params.ts', import.meta.url).pathname)

const CONNECT = ['-h', HOST, '-P', String(PORT), '--protocol=TCP', '--default-character-set=utf8mb4', '-u', USER, `-p${PASSWORD}`]

async function sql(statement) {
  const { stdout } = await run('mysql', [...CONNECT, '-N', '-B', '-e', statement], { encoding: 'utf8' })
  return stdout
}

const version = (await sql('SELECT VERSION()')).trim()
const words = (await sql('SELECT value FROM INFORMATION_SCHEMA.INNODB_FT_DEFAULT_STOPWORD')).trim().split('\n')
const [min, max] = (await sql('SELECT @@innodb_ft_min_token_size, @@innodb_ft_max_token_size')).trim().split('\t').map(Number)

// A short read would index every stopword; refuse one. 8.4 publishes 36 rows,
// 'the' among them twice.
if (words.length < 30 || !words.includes('the') || !(min >= 1) || !(max > min)) {
  console.error(`implausible full-text parameters: ${words.length} stopwords, tokens ${min}..${max}`)
  process.exit(1)
}
const unique = [...new Set(words)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))

writeFileSync(
  OUT,
  `// Generated by tools/capture-fulltext.mjs from MySQL ${version}; do not edit.
//
// InnoDB's default stopwords (INFORMATION_SCHEMA.INNODB_FT_DEFAULT_STOPWORD)
// and its token bounds (@@innodb_ft_min_token_size, @@innodb_ft_max_token_size).

export const FT_STOPWORDS: ReadonlySet<string> = new Set([${unique.map((w) => `'${w}'`).join(', ')}])
export const FT_MIN_TOKEN = ${min}
export const FT_MAX_TOKEN = ${max}
`,
)
console.log(`fulltext: ${unique.length} stopwords, tokens ${min}..${max} → ${OUT}`)
