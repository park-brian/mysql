#!/usr/bin/env node
// M3.15 — MySQL's reserved words, from a real MySQL, into `@myjs/parser`.
//
// A parser needs the reserved list before it can parse a `SELECT` at all:
// `FROM t x JOIN u` makes `x` an alias and `JOIN` not one, and only the list
// says which is which. The list is also what refuses `CREATE TABLE lateral(…)`,
// which M3.5's census found accepted here and rejected by a real server.
//
// Why a server and not `reference/` (D-39). In MySQL's source the *words* are in
// `sql/lex.h`, but whether a word is reserved is not a field anywhere — it is
// decided by which `ident_keyword*` productions of `sql/sql_yacc.yy` mention it,
// and MySQL's own build derives `INFORMATION_SCHEMA.KEYWORDS` from the grammar
// with a generator that runs on Bison's output. Re-deriving that here means
// parsing Bison, the fragility D-14 and M2.17 exist to avoid and the reason
// M3.5 wrote its type table out by hand. The server has already done the
// derivation and publishes the answer as a table, so this asks it.
//
// What is committed is facts only — a word and a flag — never anything from
// MySQL's source text, so ground rule 7 holds.
//
// Usage:
//   node tools/capture-keywords.mjs --host 127.0.0.1 --port 3306 --user root --password root
import { writeFileSync } from 'node:fs'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { arg } from './lib/cli.mjs'

const run = promisify(execFile)


const HOST = arg('host', '127.0.0.1')
const PORT = arg('port', '3306')
const USER = arg('user', 'root')
const PASSWORD = arg('password', 'root')
const OUT = arg('out', new URL('../packages/parser/src/keywords.ts', import.meta.url).pathname)

// The same connection the other capture tools use, `--default-character-set`
// pinned for the reason `capture-precedence.mjs` records.
const CONNECT = ['-h', HOST, '-P', String(PORT), '--protocol=TCP', '--default-character-set=utf8mb4', '-u', USER, `-p${PASSWORD}`]

async function sql(statement) {
  const { stdout } = await run('mysql', [...CONNECT, '-N', '-B', '-e', statement], { encoding: 'utf8' })
  return stdout
}

const version = (await sql('SELECT VERSION()')).trim()
const rows = (await sql('SELECT WORD, RESERVED FROM INFORMATION_SCHEMA.KEYWORDS'))
  .trim()
  .split('\n')
  .map((line) => line.split('\t'))

const all = rows.map(([word]) => word)
const reserved = rows.filter(([, flag]) => flag === '1').map(([word]) => word)

// A capture that silently returned nothing would make every word an
// identifier, and the parser would then accept `SELECT FROM FROM FROM`. The
// table has carried several hundred keywords since 8.0; refuse a short read.
if (all.length < 500 || reserved.length < 200) {
  console.error(`implausible keyword table: ${all.length} words, ${reserved.length} reserved`)
  process.exit(1)
}
if (!reserved.includes('SELECT') || reserved.includes('TIMESTAMP')) {
  console.error('keyword table disagrees with facts this parser already relies on (SELECT reserved, TIMESTAMP not)')
  process.exit(1)
}

// Sorted by code unit, not by locale, so the output is a pure function of the
// server's answer and re-capturing on any machine reproduces it byte for byte.
reserved.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))

const lines = []
let line = ' '
for (const word of reserved) {
  const item = ` '${word}',`
  if (line.length + item.length > 100) {
    lines.push(line)
    line = ' '
  }
  line += item
}
lines.push(line)

writeFileSync(
  OUT,
  `// GENERATED by tools/capture-keywords.mjs — do not edit (M3.15, D-39).
//
// MySQL's reserved words: \`SELECT WORD FROM INFORMATION_SCHEMA.KEYWORDS WHERE
// RESERVED = 1\` on MySQL ${version}. ${reserved.length} of its ${all.length} keywords.
//
// An unquoted reserved word is never an identifier. It may still follow a \`.\`
// in a qualified name, and it may still name a builtin function when a \`(\`
// follows (\`IF(\`, \`LEFT(\`, \`REPLACE(\`) — those are the grammar's rules, not
// the table's, and they live with the parsers that apply them.

/** Upper-case. Compare with \`word.toUpperCase()\`. */
export const RESERVED: ReadonlySet<string> = new Set([
${lines.join('\n')}
])
`,
)
console.log(`${reserved.length} reserved of ${all.length} keywords, from MySQL ${version} -> ${OUT}`)
