#!/usr/bin/env node
// M5.2 — the field type two values merge to where MySQL needs one type for
// several (CASE, IF, IFNULL, COALESCE, a UNION column), captured from a real
// server rather than read from its source (D-39).
//
// MySQL decides it pairwise, from the two field types alone, and the result
// is not what a reader would guess: a CHAR beside a DECIMAL is a CHAR, a DATE
// beside a TIME a DATETIME, a YEAR beside an INT an INT, JSON beside a number
// a LONGBLOB. The coercion corpus found the executor's hand-made rule wrong
// on all of these. So this asks: for every pair of a table's column types,
// and for NULL, what field type do `COALESCE(a, b)`, `IF(c, a, b)` and
// `CASE WHEN c THEN a ELSE b END` report? It asserts the three agree, and
// writes the one table into `@myjs/types`.
//
// Usage:
//   node tools/capture-type-merge.mjs --host 127.0.0.1 --port 3306 --user root --password root
import { writeFileSync } from 'node:fs'
import mysql from 'mysql2/promise'
import { arg } from './lib/cli.mjs'

const OUT = new URL('../packages/types/src/type-merge.ts', import.meta.url).pathname

/** Each column type, by the name the table below uses, and its DDL. */
const COLUMNS = [
  ['TINY', 'TINYINT'], ['SHORT', 'SMALLINT'], ['INT24', 'MEDIUMINT'], ['LONG', 'INT'], ['LONGLONG', 'BIGINT'],
  ['NEWDECIMAL', 'DECIMAL(10,2)'], ['FLOAT', 'FLOAT'], ['DOUBLE', 'DOUBLE'], ['BIT', 'BIT(8)'], ['YEAR', 'YEAR'],
  ['DATE', 'DATE'], ['TIME', 'TIME'], ['DATETIME', 'DATETIME'], ['TIMESTAMP', 'TIMESTAMP NULL'],
  ['STRING', 'CHAR(5)'], ['VARCHAR', 'VARCHAR(5)'], ['TINY_BLOB', 'TINYTEXT'], ['BLOB', 'TEXT'], ['MEDIUM_BLOB', 'MEDIUMTEXT'], ['LONG_BLOB', 'LONGTEXT'],
  ['ENUM', "ENUM('a','b')"], ['SET', "SET('a','b')"], ['JSON', 'JSON'],
]
/** `mysql2`'s wire codes, by name (include/field_types.h). */
const CODE = { DECIMAL: 0, TINY: 1, SHORT: 2, LONG: 3, FLOAT: 4, DOUBLE: 5, NULL: 6, TIMESTAMP: 7, LONGLONG: 8, INT24: 9, DATE: 10, TIME: 11, DATETIME: 12, YEAR: 13, NEWDATE: 14, VARCHAR: 15, BIT: 16, JSON: 245, NEWDECIMAL: 246, ENUM: 247, SET: 248, TINY_BLOB: 249, MEDIUM_BLOB: 250, LONG_BLOB: 251, BLOB: 252, VAR_STRING: 253, STRING: 254, GEOMETRY: 255 }
const NAME = Object.fromEntries(Object.entries(CODE).map(([k, v]) => [v, k]))

const conn = await mysql.createConnection({
  host: arg('host', '127.0.0.1'),
  port: Number(arg('port', '3306')),
  user: arg('user', 'root'),
  password: arg('password', 'root'),
})
const [[{ v: version }]] = await conn.query('SELECT VERSION() AS v')
await conn.query('DROP DATABASE IF EXISTS myjs_merge')
await conn.query('CREATE DATABASE myjs_merge')
await conn.query('USE myjs_merge')
await conn.query(`CREATE TABLE t (${COLUMNS.map(([n, ddl]) => `c_${n} ${ddl}`).join(', ')})`)

const operands = [...COLUMNS.map(([n]) => [n, `c_${n}`]), ['NULL', 'NULL']]
const rows = []
for (const [a, x] of operands) {
  const row = []
  for (const [b, y] of operands) {
    const [, fields] = await conn.query(`SELECT COALESCE(${x}, ${y}), IF(RAND() < 2, ${x}, ${y}), CASE WHEN RAND() < 2 THEN ${x} ELSE ${y} END FROM t`)
    const codes = fields.map((f) => f.columnType)
    if (new Set(codes).size !== 1) throw new Error(`${a} with ${b}: COALESCE, IF and CASE disagree: ${codes.join(', ')}`)
    // A VARCHAR result is VAR_STRING on the wire; the table names field types, so it says VARCHAR.
    row.push(codes[0] === CODE.VAR_STRING ? 'VARCHAR' : NAME[codes[0]])
  }
  rows.push(row)
}
await conn.query('DROP DATABASE myjs_merge')
await conn.end()

const names = operands.map(([n]) => n)
// Each row a string of letters, one per column: the merged type's index in MERGE_TYPES.
const letter = (n) => String.fromCharCode(97 + names.indexOf(n))
for (const n of rows.flat()) if (!names.includes(n)) throw new Error(`${n}: a merge to a type the table does not index`)
const body = rows.map((row, i) => `  '${row.map(letter).join('')}', // ${names[i]}`).join('\n')
writeFileSync(
  OUT,
  `// GENERATED by tools/capture-type-merge.mjs — do not edit (M5.2, D-39).
//
// The field type two values merge to where MySQL needs one type for several:
// CASE, IF, IFNULL, COALESCE. Asked of MySQL ${version}: for every pair of a
// table's column types and NULL, the type \`COALESCE(a, b)\`, \`IF(c, a, b)\` and
// \`CASE WHEN c THEN a ELSE b END\` report, which the capture checked agree.
// VARCHAR stands for both VARCHAR and VAR_STRING, which is how a VARCHAR goes
// on the wire. Row a, column b, is a letter: the merged type's place in
// MERGE_TYPES, \`a\` for the first.

export type MergeType = ${names.map((n) => `'${n}'`).join(' | ')}

/** The types in the order the table indexes them. */
export const MERGE_TYPES: readonly MergeType[] = [${names.map((n) => `'${n}'`).join(', ')}]

const TABLE: readonly string[] = [
${body}
]

/** The field type \`a\` and \`b\` merge to. */
export function mergeTypes(a: MergeType, b: MergeType): MergeType {
  return MERGE_TYPES[(TABLE[MERGE_TYPES.indexOf(a)] as string).charCodeAt(MERGE_TYPES.indexOf(b)) - 97] as MergeType
}
`,
)
console.log(`${names.length} × ${names.length} merges from ${version} -> ${OUT}`)
