function fields(columns: mysql.FieldPacket[]) {
  return columns.map(f => [f.name,f.columnType,f.columnLength,f.flags,f.decimals,f.characterSet,f.schema,f.table,f.orgTable,f.orgName])
}

test('table expression bytes retain all byte-valued characters through both protocols', async () => {
  const host = process.env['MYSQL_REFERENCE_HOST']
  const db = host === undefined ? await MySQL.open(':memory:') : undefined
  const conn = await mysql.createConnection(db === undefined ? {host:host as string,user:'root',password:process.env['MYSQL_REFERENCE_PASSWORD'] ?? ''} : {stream:db.createStream(),user:'root'})
  const values = [...Array.from({length:256},(_,i) => 'G'+String.fromCharCode(i)+'G'),"G'G",'G\\G','G\0\n\r\x1a\t\b\\\'G','',null]
  try {
    await conn.query('CREATE DATABASE literal_controls72')
    await conn.query('USE literal_controls72')
    for (const [id,value] of values.entries()) for (const prefix of ['','_utf8mb4','_latin1','_binary']) {
      const literal = value === null ? 'NULL' : prefix+mysql.escape(value)
      const ddl = 'CREATE TABLE t (b VARCHAR(16),s VARCHAR(16) AS ('+literal+'),d VARCHAR(16) DEFAULT ('+literal+'),CONSTRAINT c CHECK (b <> '+literal+'))'
      await conn.query('DO 0')
      const [created] = await conn.query(ddl)
      assert.deepEqual([JSON.parse(JSON.stringify(created)),(await conn.query('SHOW WARNINGS'))[0]],CREATED)
      const written = value === null ? 'NULL' : (prefix || '_utf8mb4')+PRINTED[id]
      const escaped = value === null ? 'NULL' : (prefix || '_utf8mb4')+INFORMATION[id]
      const show = 'CREATE TABLE `t` (\n  `b` varchar(16) DEFAULT NULL,\n  `s` varchar(16) GENERATED ALWAYS AS ('+written+') VIRTUAL,\n  `d` varchar(16) DEFAULT ('+written+'),\n  CONSTRAINT `c` CHECK ((`b` <> '+written+'))\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci'
      const cases = [
        ["SELECT GENERATION_EXPRESSION FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='literal_controls72' AND TABLE_NAME='t' AND COLUMN_NAME='s'",[[escaped]],FIELDS[1]],
        ["SELECT CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS WHERE CONSTRAINT_SCHEMA='literal_controls72' AND CONSTRAINT_NAME='c'",[['(`b` <> '+escaped+')']],FIELDS[2]],
        ['SHOW CREATE TABLE t',[['t',show]],FIELDS[3]],
      ] as const
      for (const [sql,expected,metadata] of cases) for (const method of ['query','execute'] as const) {
        await conn.query('DO 0')
        const options = {sql,rowsAsArray:true}
        const [rows,columns] = method === 'query' ? await conn.query(options) : await conn.execute(options)
        assert.deepEqual([rows,fields(columns),(await conn.query('SHOW WARNINGS'))[0]],[expected,metadata,[]],JSON.stringify({id,prefix,method,sql}))
        conn.unprepare(options)
      }
      await conn.query('DROP TABLE t')
    }
  } finally {
    await conn.query('DROP DATABASE IF EXISTS literal_controls72')
    await conn.end()
    await db?.end()
  }
})
