test('table expression source charset survives fresh definitions and cached reads', async () => {
  const host = process.env['MYSQL_REFERENCE_HOST']
  const db = host === undefined ? await MySQL.open(':memory:') : undefined
  const open = (charset: string) => mysql.createConnection(db === undefined ? {host:host as string,user:'root',password:process.env['MYSQL_REFERENCE_PASSWORD'] ?? '',charset} : {stream:db.createStream(),user:'root',charset})
  const reader = await open('utf8mb4_unicode_ci')
  const creators = new Map<string,mysql.Connection>()
  const statements: {options:{sql:string;rowsAsArray:boolean};stmt:mysql.PreparedStatementInfo}[] = []
  const values = [...Array.from({length:256},(_,i) => 'G'+String.fromCharCode(i)+'G').filter((_,i) => [0,8,9,10,13,26,39,92,127,128,129,159,160,233,255].includes(i)),"G'\\\0\n\r\x1a\t\bG",'',null,'G€G','G😀G','\ufeffG','G\ufeffG','GΩG','Gé'.repeat(4096),'G'.repeat(70000)+'é']
  try {
    await reader.query('CREATE DATABASE expression_fresh75')
    await reader.query('USE expression_fresh75')
    await reader.query("CREATE TABLE t(c VARCHAR(100),g VARCHAR(100) AS ('G'),CONSTRAINT ck CHECK(c <> 'G'))")
    const queries = [
      "SELECT GENERATION_EXPRESSION FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='expression_fresh75' AND TABLE_NAME='t' AND COLUMN_NAME='g'",
      "SELECT CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS WHERE CONSTRAINT_SCHEMA='expression_fresh75' AND CONSTRAINT_NAME='ck'",
      'SHOW CREATE TABLE t',
    ]
    for (const [i,sql] of queries.entries()) {
      await reader.query('DO 0')
      const options = {sql,rowsAsArray:true}, stmt = await reader.prepare(options)
      statements.push({options,stmt})
      const resolved = stmt as unknown as {statement:{columns:mysql.FieldPacket[]}}
      assert.deepEqual([fields(resolved.statement.columns),(await reader.query('SHOW WARNINGS'))[0]],PREPARE[i])
    }
    for (const [charset,id,prefix,form,expected] of FRESH) {
      let creator = creators.get(charset)
      if (creator === undefined) {
        creator = await open(charset)
        creators.set(charset,creator)
        await creator.query('USE expression_fresh75')
      }
      await reader.query('DROP TABLE IF EXISTS t')
      const value = values[id]!, literal = value === null ? 'NULL' : prefix+mysql.escape(value)
      const expression = form === 'literal' ? literal : 'CONCAT(c,'+literal+')'
      const sql = 'CREATE TABLE t(c VARCHAR(100),g VARCHAR(100) AS ('+expression+'),CONSTRAINT ck CHECK(c <> '+expression+'))'
      await creator.query('DO 0')
      const [created,columns] = await creator.query(sql)
      const [createRows,createFields,createWarnings] = OUTCOMES[expected[0]!]!
      assert.deepEqual([JSON.parse(JSON.stringify(created)),columns === undefined ? [] : fields(columns),(await creator.query('SHOW WARNINGS'))[0]],[createRows,FIELDS[createFields],createWarnings])
      for (const [g,{options,stmt}] of statements.entries()) for (const [m,method] of (['query','execute','statement'] as const).entries()) {
        const index = expected[1+g*3+m]
        if (index === undefined) continue
        await reader.query('DO 0')
        const [rows,columns] = method === 'statement' ? await stmt.execute([]) : method === 'query' ? await reader.query(options) : await reader.execute(options)
        const [result,metadata,warnings] = OUTCOMES[index]!
        assert.deepEqual([rows,fields(columns),(await reader.query('SHOW WARNINGS'))[0]],[method === 'statement' ? (result as unknown[][]).map(row => Object.fromEntries((FIELDS[metadata] as unknown[][]).map((f,i) => [f[0] as string,row[i]]))) : result,FIELDS[metadata],warnings],JSON.stringify({charset,id,prefix,form,group:g,method}))
      }
    }
  } finally {
    for (const {options,stmt} of statements) { await stmt.close(); reader.unprepare(options) }
    await reader.query('DROP DATABASE IF EXISTS expression_fresh75')
    for (const creator of creators.values()) await creator.end()
    await reader.end()
    await db?.end()
  }
})


