function fields(columns: mysql.FieldPacket[]) {
  return columns.map(f => [f.name,f.columnType,f.columnLength,f.flags,f.decimals,f.characterSet,f.schema,f.table,f.orgTable,f.orgName])
}
function expression(text: string, form: string) {
  if (form === 'concat') return 'concat('+text+')'
  if (form === 'if') return 'if(1,'+text+',NULL)'
  return text
}

test('view literal introducers follow explicit SHOW context across fresh cached definitions', async () => {
  const host = process.env['MYSQL_REFERENCE_HOST']
  const db = host === undefined ? await MySQL.open(':memory:') : undefined
  const open = () => mysql.createConnection(db === undefined ? {host:host as string,user:'root',password:process.env['MYSQL_REFERENCE_PASSWORD'] ?? ''} : {stream:db.createStream(),user:'root'})
  const conn = await open(), reader = await open(), foreign = await open()
  const values = [...Array.from({length:256},(_,i) => 'G'+String.fromCharCode(i)+'G'),"G'G",'G\\G','G\0\n\r\x1a\t\b\\\'G','',null,'GéG','G€G','G😀G','G\ufeffG','GΩG']
  const introspection = "SELECT VIEW_DEFINITION FROM information_schema.VIEWS WHERE TABLE_SCHEMA='view_context_nested74' AND TABLE_NAME='v'"
  const statements: {conn:mysql.Connection;group:string;options:{sql:string;rowsAsArray:boolean};stmt:mysql.PreparedStatementInfo}[] = []
  try {
    await conn.query('CREATE DATABASE view_context_nested74_other')
    await foreign.query('USE view_context_nested74_other')
    await conn.query('CREATE DATABASE view_context_nested74')
    await conn.query('USE view_context_nested74')
    await conn.query('CREATE TABLE t(id INT)')
    await conn.query("CREATE VIEW v AS SELECT 'G' AS x,id FROM t")
    for (const [c,group,sql] of [[conn,'selected','SHOW CREATE VIEW v'],[reader,'unselected','SHOW CREATE VIEW view_context_nested74.v'],[foreign,'foreign','SHOW CREATE VIEW view_context_nested74.v'],[conn,'information',introspection]] as const) {
      await c.query('DO 0')
      const options = {sql,rowsAsArray:true}, stmt = await c.prepare(options)
      statements.push({conn:c,group,options,stmt})
      assert.deepEqual(fields((stmt as unknown as {statement:{columns:mysql.FieldPacket[]}}).statement.columns),group === 'information' ? INFORMATION_FIELDS : [])
      assert.deepEqual((await c.query('SHOW WARNINGS'))[0],[])
    }
    for (const [id,value] of values.entries()) for (const [p,prefix] of ['','_utf8mb4','_latin1','_binary'].entries()) for (const form of ['literal','concat','if']) {
      const literal = value === null ? 'NULL' : prefix+mysql.escape(value)
      await conn.query('DROP VIEW v')
      await conn.query('CREATE VIEW v AS SELECT '+expression(literal,form)+' AS x,id FROM t')
      for (const {conn:c,group,options,stmt} of statements) {
        const information = group === 'information'
        // Admission is explicit by input/configuration, never by runtime equality.
        if (information && (p < 2 ? id === 263 : !(id < 128 || id >= 256 && id <= 260))) continue
        const qualified = group !== 'selected'
        const table = qualified ? '`view_context_nested74`.`t`' : '`t`'
        const view = qualified ? '`view_context_nested74`.`v`' : '`v`'
        const text = expression(information ? INFORMATION[p]![id]! : value === null ? 'NULL' : prefix+PRINTED[id],form)
        const definition = 'select '+text+' AS `x`,'+table+'.`id` AS `id` from '+table
        const row = information ? [definition] : ['v','CREATE ALGORITHM=UNDEFINED DEFINER=`root`@`%` SQL SECURITY DEFINER VIEW '+view+' AS '+definition,'utf8mb4','utf8mb4_unicode_ci']
        for (const method of ['query','execute','statement'] as const) {
          await c.query('DO 0')
          const [rows,columns] = method === 'statement' ? await stmt.execute([]) : method === 'query' ? await c.query(options) : await c.execute(options)
          const expectedRows = method === 'statement' ? [Object.fromEntries((information ? ['VIEW_DEFINITION'] : SHOW_COLUMNS).map((key,i) => [key,row[i]]))] : [row]
          assert.deepEqual([rows,fields(columns),(await c.query('SHOW WARNINGS'))[0]],[expectedRows,information ? INFORMATION_FIELDS : SHOW_FIELDS,[]],JSON.stringify({id,prefix,form,group,method}))
        }
      }
    }
  } finally {
    for (const {conn:c,options,stmt} of statements) { await stmt.close(); c.unprepare(options) }
    await conn.query('DROP DATABASE IF EXISTS view_context_nested74')
    await conn.query('DROP DATABASE IF EXISTS view_context_nested74_other')
    await foreign.end()
    await reader.end()
    await conn.end()
    await db?.end()
  }
})
